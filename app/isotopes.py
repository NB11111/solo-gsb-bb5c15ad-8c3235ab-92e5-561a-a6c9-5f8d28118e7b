def isotope_by_mass_number(symbol: str, mass_number: int) -> tuple[float, float] | None:
    """Return the (mass, abundance) of ``symbol``'s isotope with the given
    mass number, or ``None`` if no such isotope is known."""
    for mass, abundance in ISOTOPES.get(symbol, ()):  # unknown symbol -> None
        if round(mass) == mass_number:
            return mass, abundance
    return None


def most_abundant_isotope_mass(symbol: str) -> float:
    """Mass of the most abundant natural isotope (monoisotopic convention)."""
    return max(ISOTOPES[symbol], key=lambda iso: iso[1])[0]
